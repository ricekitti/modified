    public static final class Chat {
        public static final char SECTION = '§';

        public static String strip(String s) {
            if (s == null || s.isEmpty()) {
                return "";
            }
            StringBuilder sb = new StringBuilder(s.length());
            boolean skip = false;
            for (int i = 0; i < s.length(); ++i) {
                char c = s.charAt(i);
                if (skip) {
                    skip = false;
                    continue;
                }
                if (c == SECTION) {
                    skip = true;
                    continue;
                }
                if (c <= '\u0014' || c >= '\u007f') continue;
                sb.append(c);
            }
            return sb.toString();
        }
    }

