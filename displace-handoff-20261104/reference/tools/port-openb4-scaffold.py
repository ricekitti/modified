KEEP_IMPORT = re.compile(r'^import (?:static )?(?:net\.minecraft\.|java\.|javax\.|org\.lwjgl\.|com\.google\.)')


def skip_literal(text, i):
    quote = text[i]
    i += 1
    while text[i] != quote:
        i += 2 if text[i] == '\\' else 1
    return i + 1


def skip_noise(text, i):
    """If i is at a literal or comment, return the index past it; else None."""
    if text[i] in '"\'':
        return skip_literal(text, i)
    if text.startswith('//', i):
        return text.index('\n', i)
    if text.startswith('/*', i):
        return text.index('*/', i) + 2
    return None


def block_end(text, start):
    i = text.index('{', start)
    depth = 0
    while True:
        j = skip_noise(text, i)
        if j is not None:
            i = j
            continue
        c = text[i]
        if c == '{':
            depth += 1
        elif c == '}':
            depth -= 1
            if depth == 0:
                return i + 1
        i += 1


def member_end(text, k):
    """End of the class-level member starting at k: ';' for plain fields, the closing brace for methods/types/init
    blocks, and the terminating ';' for field initializers (including multi-line and brace-initialised arrays)."""
    i, paren = k, 0
    while True:
        j = skip_noise(text, i)
        if j is not None:
            i = j
            continue
        c = text[i]
        if c == '(':
            paren += 1
        elif c == ')':
            paren -= 1
        elif paren == 0 and c in '{;=':
            break
        i += 1
    if text[i] == ';':
        return i + 1
    if text[i] == '{':
        return block_end(text, k)
    depth = 0
    while True:
        j = skip_noise(text, i)
        if j is not None:
            i = j
            continue
        c = text[i]
        if c in '({[':
            depth += 1
        elif c in ')}]':
            depth -= 1
        elif c == ';' and depth == 0:
            return i + 1
        i += 1


def find_line(text, line, where):
    hits = [m.start() for m in re.finditer('(?m)^' + re.escape(line) + '$', text)]
    if len(hits) != 1:
        raise SystemExit('%s: expected exactly one "%s", found %d' % (where, line.strip(), len(hits)))
    return hits[0]


def extract(text, line, where):
    k = find_line(text, line, where)
    return text[k:member_end(text, k)] + '\n'


def whole_type(text, name, where):
    m = re.search(r'(?m)^public (final )?(class|enum) ' + re.escape(name) + r'\b[^\n]*\{$', text)
    if not m:
        raise SystemExit('%s: no top-level declaration for %s' % (where, name))
    body = text[m.start():].rstrip()
    if not body.endswith('}'):
        raise SystemExit('%s: unexpected tail' % where)
    if m.group(2) == 'class':  # nested classes must be static; nested enums already are
        body = re.sub(r'^public (final )?class ', lambda g: 'public static ' + (g.group(1) or '') + 'class ', body, count=1)
    return body + '\n'


def indent(block):
    return ''.join(('    ' + l if l.strip() else l) for l in block.splitlines(True))


def apply_rules(block, scope, manifest):
    for pattern, repl, reason in RULES:
        block, n = re.subn(pattern, repl, block)
        if n:
            manifest['rules'].setdefault(reason, {})[scope] = n
    return block


def apply_rewrites(block, scope, applied):
    for s, old, new, count, reason in REWRITES:
        if s != scope:
            continue
        found = block.count(old)
        if found != count:
            raise SystemExit('rewrite in %s expected %d match(es), found %d: %r' % (scope, count, found, old[:80]))
        block = block.replace(old, new)
        applied.add(s)
    return block


def generate(src):
    manifest = {'source': 'OpenB4-u20 (local download, read-only)', 'files': {}, 'whole': {}, 'members': {},
                'fragments': {}, 'rules': {}, 'rewrites': []}
    applied = set()
    imports = {}
    nested = set()
    sections = []

    def read(path):
        raw = (src / path).read_bytes()
        manifest['files'][path] = hashlib.sha256(raw).hexdigest()
        text = raw.decode('utf-8').replace('\r\n', '\n')
        for imp in re.findall(r'(?m)^import [^;]+;', text):
            name = imp[len('import '):-1].replace('static ', '')
            name = FORGE_IMPORT_MAP.get(name, name)
            if KEEP_IMPORT.match('import ' + name) or name in FORGE_IMPORT_MAP.values():
                imports.setdefault(name.rsplit('.', 1)[-1], set()).add(name)
        return text

    for name, path in WHOLE:
        body = whole_type(read(path), name, path)
        manifest['whole'][path] = hashlib.sha256(body.encode('utf-8')).hexdigest()
        body = apply_rewrites(apply_rules(body, name, manifest), name, applied)
        nested.add(name)
        sections.append('\n    // ---- verbatim from %s (whole) ----\n%s' % (path, indent(body)))

    for name, path, lines in MEMBERS:
        text = read(path)
        parts = []
        for line in lines:
            member = extract(text, line, path)
            manifest['members']['%s :: %s' % (path, line.strip())] = hashlib.sha256(member.encode('utf-8')).hexdigest()
            parts.append(member)
        block = apply_rewrites(apply_rules('\n'.join(parts), name, manifest), name, applied)
        nested.add(name)
        sections.append('\n    // ---- verbatim from %s ----\n    public static final class %s {\n%s    }\n'
                        % (path, name, indent(block)))

    for name, path, lines, method, head in FRAGMENTS:
        text = read(path)
        parts = [extract(text, line, path) for line in lines]
        k = find_line(text, head, path)
        frag = text[k:block_end(text, k)] + '\n'
        manifest['fragments']['%s :: %s' % (path, head.strip())] = hashlib.sha256(frag.encode('utf-8')).hexdigest()
        for line, member in zip(lines, parts):
            manifest['members']['%s :: %s' % (path, line.strip())] = hashlib.sha256(member.encode('utf-8')).hexdigest()
        block = '\n'.join(parts) + '\n    public static void %s() {\n%s    }\n' % (method, frag)
        block = apply_rewrites(apply_rules(block, name, manifest), name, applied)
        nested.add(name)
        sections.append('\n    // ---- verbatim from %s (members + fragment; %s() is the generated wrapper) ----\n'
                        '    public static final class %s {\n%s    }\n' % (path, method, name, indent(block)))

    for s, old, new, count, reason in REWRITES:
        if s not in applied:
            raise SystemExit('rewrite scope never applied: ' + s)
        manifest['rewrites'].append({'scope': s, 'old': old, 'new': new, 'count': count, 'reason': reason})

    kept = []
    for simple, names in sorted(imports.items()):
        if simple in nested:
            continue  # the nested OpenB4 class of the same name wins
        if len(names) != 1:
            raise SystemExit('ambiguous import %s: %s' % (simple, sorted(names)))
        kept.append('import %s;' % next(iter(names)))
    out = HEADER % ('\n'.join(kept) + '\n') + ''.join(sections) + '}\n'
    return out, manifest


def main():
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    out_path = Path(sys.argv[sys.argv.index('--out') + 1]) if '--out' in sys.argv else OUT
    man_path = Path(sys.argv[sys.argv.index('--manifest') + 1]) if '--manifest' in sys.argv else MANIFEST
    text, manifest = generate(Path(sys.argv[1]))
    if '--check' in sys.argv:
        bad = []
        if not out_path.exists() or out_path.read_text(encoding='utf-8') != text:
            bad.append(str(out_path))
        if not man_path.exists() or json.loads(man_path.read_text(encoding='utf-8')) != manifest:
            bad.append(str(man_path))
        if bad:
            raise SystemExit('OpenB4 Scaffold port drifted from upstream:\n  ' + '\n  '.join(bad))
        print('PASS: OpenB4ScaffoldBackend equals OpenB4-u20 Scaffold/Tower/AutoSwap + %d whole type(s) + %d member(s) + '
              '%d fragment(s) + %d whitelisted rewrite(s)' % (len(manifest['whole']), len(manifest['members']),
                                                              len(manifest['fragments']), len(REWRITES)))
        return
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(text, encoding='utf-8', newline='\n')
    man_path.write_text(json.dumps(manifest, indent=1, sort_keys=True, ensure_ascii=False) + '\n', encoding='utf-8', newline='\n')
    casts = sorted(set(re.findall(r'\((I[A-Z][A-Za-z]+)\)\s*\w', text)))
    print('generated %s: %d whole, %d members, %d fragments, %d lines' % (out_path, len(manifest['whole']),
          len(manifest['members']), len(manifest['fragments']), text.count('\n')))
    if casts:
        print('WARNING: interface casts left in output (compile fine, fail at runtime): ' + ', '.join(casts))


if __name__ == '__main__':
    main()
